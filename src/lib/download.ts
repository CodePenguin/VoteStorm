/** A file name from the Storm's name (plain lower-case letters and digits joined by dashes), or from its code when the name gives nothing. */
export function fileSlug(name: string | null | undefined, stormCode: string): string {
  const slug = (name ?? '')
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .slice(0, 60)
    .replace(/^-+|-+$/g, '');
  return slug || `storm-${stormCode.toLowerCase()}`;
}

/** Hands the browser a file to save. */
export function downloadText(fileName: string, text: string, type: string): void {
  const url = URL.createObjectURL(new Blob([text], { type }));
  const link = document.createElement('a');
  link.href = url;
  link.download = fileName;
  document.body.appendChild(link);
  link.click();
  link.remove();
  // Let the URL go only once the browser has started the save.
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/** The text of a file the presenter chose. */
export function readFileText(file: Blob): Promise<string> {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(String(reader.result ?? ''));
    reader.onerror = () => reject(reader.error ?? new Error('Could not read the file'));
    reader.readAsText(file);
  });
}
